#!/usr/bin/env node
/**
 * Dalimss News → WordPress Migration Script
 * 
 * Converts articles from JSON backup into WordPress WXR (WordPress eXtended RSS) XML format.
 * The generated XML can be imported via WordPress Dashboard → Tools → Import → WordPress.
 * 
 * Usage: node scripts/migrate-to-wordpress.js
 * Output: dalimss-wordpress-import.xml (in project root)
 */

const fs = require('fs');
const path = require('path');

// Load articles
const articlesPath = path.join(__dirname, '..', '..', 'Downloads', 'dalimss-articles-backup.json');
const outputPath = path.join(__dirname, '..', 'dalimss-wordpress-import.xml');

console.log('📰 Dalimss News → WordPress Migration Tool');
console.log('==========================================\n');

let articles;
try {
  const raw = fs.readFileSync(articlesPath, 'utf-8');
  articles = JSON.parse(raw);
  console.log(`✅ Loaded ${articles.length} articles from backup\n`);
} catch (err) {
  console.error('❌ Error loading articles:', err.message);
  process.exit(1);
}

// Helper: Escape XML special characters
function escapeXml(str) {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

// Helper: Wrap content in CDATA
function cdata(str) {
  if (!str) return '<![CDATA[]]>';
  // Escape any ]]> inside the content
  const safe = str.replace(/\]\]>/g, ']]]]><![CDATA[>');
  return `<![CDATA[${safe}]]>`;
}

// Helper: Format date for WordPress (YYYY-MM-DD HH:MM:SS)
function formatWpDate(isoDate) {
  const d = new Date(isoDate);
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

// Helper: Format date for RSS (RFC 822)
function formatRssDate(isoDate) {
  return new Date(isoDate).toUTCString();
}

// Collect unique categories
const categories = [...new Set(articles.map(a => a.category).filter(Boolean))];
console.log(`📂 Categories found: ${categories.join(', ')}`);

// Collect unique authors
const authors = [...new Set(articles.map(a => a.customAuthor || 'Dalimss News').filter(Boolean))];
console.log(`✍️  Authors found: ${authors.length}`);

// Map category to WordPress-friendly slug
function categorySlug(cat) {
  return cat.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');
}

// Map author to WordPress-friendly login
function authorLogin(name) {
  return name.toLowerCase().replace(/\s+/g, '_').replace(/[^a-z0-9_]/g, '');
}

// Convert Instagram/YouTube embeds in content to WordPress-compatible format
function convertEmbeds(content) {
  if (!content) return '';
  
  let result = content;
  
  // Convert Instagram reel URLs to embed blocks
  result = result.replace(
    /https?:\/\/www\.instagram\.com\/reel\/([A-Za-z0-9_-]+)\/?[^\s]*/g,
    '\n<!-- wp:embed {"url":"https://www.instagram.com/reel/$1/","type":"rich","providerNameSlug":"instagram"} -->\n<figure class="wp-block-embed is-type-rich is-provider-instagram wp-block-embed-instagram"><div class="wp-block-embed__wrapper">\nhttps://www.instagram.com/reel/$1/\n</div></figure>\n<!-- /wp:embed -->\n'
  );
  
  // Convert Instagram post URLs to embed blocks
  result = result.replace(
    /https?:\/\/www\.instagram\.com\/p\/([A-Za-z0-9_-]+)\/?[^\s]*/g,
    '\n<!-- wp:embed {"url":"https://www.instagram.com/p/$1/","type":"rich","providerNameSlug":"instagram"} -->\n<figure class="wp-block-embed is-type-rich is-provider-instagram wp-block-embed-instagram"><div class="wp-block-embed__wrapper">\nhttps://www.instagram.com/p/$1/\n</div></figure>\n<!-- /wp:embed -->\n'
  );
  
  // Wrap paragraphs properly
  result = result
    .split('\n\n')
    .map(p => {
      p = p.trim();
      if (!p) return '';
      // Don't wrap if it's already an HTML block or WP block
      if (p.startsWith('<') || p.startsWith('<!--')) return p;
      return `<p>${p}</p>`;
    })
    .filter(Boolean)
    .join('\n\n');
  
  return result;
}

// Build the WXR XML
console.log('\n🔨 Building WordPress import file...\n');

let xml = `<?xml version="1.0" encoding="UTF-8" ?>
<!-- WordPress WXR Export File -->
<!-- Generated by Dalimss News Migration Tool -->
<!-- Import this via WordPress Dashboard → Tools → Import → WordPress -->

<rss version="2.0"
  xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/"
  xmlns:content="http://purl.org/rss/1.0/modules/content/"
  xmlns:wfw="http://wellformedweb.org/CommentAPI/"
  xmlns:dc="http://purl.org/dc/elements/1.1/"
  xmlns:wp="http://wordpress.org/export/1.2/"
>
<channel>
  <title>Dalimss News</title>
  <link>https://dalimss.news</link>
  <description>Dalimss News - Varanasi's Leading Digital News Platform</description>
  <pubDate>${formatRssDate(new Date().toISOString())}</pubDate>
  <language>en</language>
  <wp:wxr_version>1.2</wp:wxr_version>
  <wp:base_site_url>https://dalimss.news</wp:base_site_url>
  <wp:base_blog_url>https://dalimss.news</wp:base_blog_url>

`;

// Add authors
authors.forEach((author, idx) => {
  xml += `  <wp:author>
    <wp:author_id>${idx + 1}</wp:author_id>
    <wp:author_login>${cdata(authorLogin(author))}</wp:author_login>
    <wp:author_email>${cdata(authorLogin(author) + '@dalimss.news')}</wp:author_email>
    <wp:author_display_name>${cdata(author)}</wp:author_display_name>
    <wp:author_first_name>${cdata(author.split(' ')[0])}</wp:author_first_name>
    <wp:author_last_name>${cdata(author.split(' ').slice(1).join(' '))}</wp:author_last_name>
  </wp:author>
`;
});

// Add categories
categories.forEach((cat, idx) => {
  xml += `  <wp:category>
    <wp:term_id>${idx + 1}</wp:term_id>
    <wp:category_nicename>${cdata(categorySlug(cat))}</wp:category_nicename>
    <wp:category_parent></wp:category_parent>
    <wp:cat_name>${cdata(cat)}</wp:cat_name>
  </wp:category>
`;
});

// Add articles as posts
let postId = 100; // Start from 100 to avoid conflicts
let attachmentId = 10000;
const mediaItems = []; // Track media for attachment posts

articles.forEach((article, idx) => {
  postId++;
  const author = article.customAuthor || 'Dalimss News';
  const category = article.category || 'General';
  const wpDate = formatWpDate(article.createdAt);
  const wpDateGmt = formatWpDate(new Date(article.createdAt).toISOString());
  const processedContent = convertEmbeds(article.content);
  
  // Create the post item
  xml += `
  <!-- Article ${idx + 1}: ${escapeXml(article.title)} -->
  <item>
    <title>${escapeXml(article.title)}</title>
    <link>https://dalimss.news/articles/${escapeXml(article.slug)}</link>
    <pubDate>${formatRssDate(article.createdAt)}</pubDate>
    <dc:creator>${cdata(authorLogin(author))}</dc:creator>
    <guid isPermaLink="false">https://dalimss.news/?p=${postId}</guid>
    <description></description>
    <content:encoded>${cdata(processedContent)}</content:encoded>
    <excerpt:encoded>${cdata(article.metaDescription || '')}</excerpt:encoded>
    <wp:post_id>${postId}</wp:post_id>
    <wp:post_date>${wpDate}</wp:post_date>
    <wp:post_date_gmt>${wpDateGmt}</wp:post_date_gmt>
    <wp:post_modified>${wpDate}</wp:post_modified>
    <wp:post_modified_gmt>${wpDateGmt}</wp:post_modified_gmt>
    <wp:comment_status>open</wp:comment_status>
    <wp:ping_status>open</wp:ping_status>
    <wp:post_name>${cdata(article.slug)}</wp:post_name>
    <wp:status>publish</wp:status>
    <wp:post_parent>0</wp:post_parent>
    <wp:menu_order>0</wp:menu_order>
    <wp:post_type>post</wp:post_type>
    <wp:post_password></wp:post_password>
    <wp:is_sticky>0</wp:is_sticky>
    <category domain="category" nicename="${escapeXml(categorySlug(category))}">${cdata(category)}</category>
`;

  // Add SEO meta (compatible with Yoast SEO plugin)
  if (article.metaTitle) {
    xml += `    <wp:postmeta>
      <wp:meta_key>_yoast_wpseo_title</wp:meta_key>
      <wp:meta_value>${cdata(article.metaTitle)}</wp:meta_value>
    </wp:postmeta>
`;
  }
  if (article.metaDescription) {
    xml += `    <wp:postmeta>
      <wp:meta_key>_yoast_wpseo_metadesc</wp:meta_key>
      <wp:meta_value>${cdata(article.metaDescription)}</wp:meta_value>
    </wp:postmeta>
`;
  }
  if (article.focusKeyword) {
    xml += `    <wp:postmeta>
      <wp:meta_key>_yoast_wpseo_focuskw</wp:meta_key>
      <wp:meta_value>${cdata(article.focusKeyword.trim())}</wp:meta_value>
    </wp:postmeta>
`;
  }
  
  // Add read time meta
  xml += `    <wp:postmeta>
      <wp:meta_key>read_time_minutes</wp:meta_key>
      <wp:meta_value>${cdata(String(article.readTimeInMinutes || 3))}</wp:meta_value>
    </wp:postmeta>
`;

  // Add custom author meta
  if (article.customAuthor) {
    xml += `    <wp:postmeta>
      <wp:meta_key>custom_author</wp:meta_key>
      <wp:meta_value>${cdata(article.customAuthor)}</wp:meta_value>
    </wp:postmeta>
`;
  }

  // Add featured image URL as meta (for plugins like "Featured Image from URL")
  if (article.mediaUrl) {
    xml += `    <wp:postmeta>
      <wp:meta_key>_thumbnail_ext_url</wp:meta_key>
      <wp:meta_value>${cdata(article.mediaUrl)}</wp:meta_value>
    </wp:postmeta>
    <wp:postmeta>
      <wp:meta_key>fifu_image_url</wp:meta_key>
      <wp:meta_value>${cdata(article.mediaUrl)}</wp:meta_value>
    </wp:postmeta>
`;
    // Store for attachment creation
    mediaItems.push({
      postId: postId,
      attachmentId: ++attachmentId,
      url: article.mediaUrl,
      title: article.title,
      date: article.createdAt
    });
  }

  // Add source URL meta
  if (article.sourceUrl) {
    xml += `    <wp:postmeta>
      <wp:meta_key>source_url</wp:meta_key>
      <wp:meta_value>${cdata(article.sourceUrl)}</wp:meta_value>
    </wp:postmeta>
`;
  }

  xml += `  </item>
`;
});

// Add media attachments (so WordPress knows about featured images)
mediaItems.forEach((media) => {
  const wpDate = formatWpDate(media.date);
  xml += `
  <item>
    <title>${escapeXml(media.title)} - Featured Image</title>
    <link>${escapeXml(media.url)}</link>
    <pubDate>${formatRssDate(media.date)}</pubDate>
    <dc:creator>admin</dc:creator>
    <guid isPermaLink="false">${escapeXml(media.url)}</guid>
    <description></description>
    <content:encoded>${cdata('')}</content:encoded>
    <excerpt:encoded>${cdata('')}</excerpt:encoded>
    <wp:post_id>${media.attachmentId}</wp:post_id>
    <wp:post_date>${wpDate}</wp:post_date>
    <wp:post_date_gmt>${wpDate}</wp:post_date_gmt>
    <wp:post_modified>${wpDate}</wp:post_modified>
    <wp:post_modified_gmt>${wpDate}</wp:post_modified_gmt>
    <wp:comment_status>closed</wp:comment_status>
    <wp:ping_status>closed</wp:ping_status>
    <wp:post_name>${cdata('attachment-' + media.attachmentId)}</wp:post_name>
    <wp:status>inherit</wp:status>
    <wp:post_parent>${media.postId}</wp:post_parent>
    <wp:menu_order>0</wp:menu_order>
    <wp:post_type>attachment</wp:post_type>
    <wp:post_password></wp:post_password>
    <wp:is_sticky>0</wp:is_sticky>
    <wp:attachment_url>${escapeXml(media.url)}</wp:attachment_url>
    <wp:postmeta>
      <wp:meta_key>_wp_attached_file</wp:meta_key>
      <wp:meta_value>${cdata(media.url)}</wp:meta_value>
    </wp:postmeta>
  </item>
`;
});

// Close the XML
xml += `
</channel>
</rss>
`;

// Write the file
fs.writeFileSync(outputPath, xml, 'utf-8');

const fileSizeMB = (Buffer.byteLength(xml, 'utf-8') / (1024 * 1024)).toFixed(2);
console.log(`✅ WordPress import file generated!`);
console.log(`📄 File: ${outputPath}`);
console.log(`📊 Size: ${fileSizeMB} MB`);
console.log(`📰 Articles: ${articles.length}`);
console.log(`📂 Categories: ${categories.length} (${categories.join(', ')})`);
console.log(`✍️  Authors: ${authors.length}`);
console.log(`🖼️  Media attachments: ${mediaItems.length}`);
